// Regenerate with `npm run icons:metronome`. Requires ImageMagick 7.
// Normal Mix builds use the committed exports, as with the calendar icons.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const {execFileSync} = require('child_process');

const root = path.resolve(__dirname, '..');
const source = path.join(root, 'resources/artwork/metronome/icon.svg');
const output = path.join(root, 'public/favicon/metronome');
const blue = '#155eef';
const artwork = fs.readFileSync(source, 'utf8');
const version = crypto.createHash('sha256').update(artwork)
    .update(fs.readFileSync(__filename)).digest('hex').slice(0, 12);

// CSS screen sizes and pixel ratios. Keep both orientations for iPhone/iPad.
const screens = [
    [320, 568, 2], [375, 667, 2], [414, 736, 3],
    [375, 812, 3], [390, 844, 3], [393, 852, 3],
    [402, 874, 3], [414, 896, 2], [414, 896, 3],
    [420, 912, 3], [428, 926, 3], [430, 932, 3], [440, 956, 3],
    [744, 1133, 2], [768, 1024, 2], [810, 1080, 2],
    [820, 1180, 2], [834, 1112, 2], [834, 1194, 2],
    [834, 1210, 2], [1024, 1366, 2], [1032, 1376, 2],
];

execFileSync('magick', ['-version'], {stdio: 'ignore'});
fs.mkdirSync(output, {recursive: true});

function render(input, filename, operations = []) {
    execFileSync('magick', [
        input, '-colorspace', 'sRGB', '-filter', 'Lanczos', ...operations,
        '-background', blue, '-alpha', 'remove', '-alpha', 'off',
        '-depth', '8', '-strip', '-define', 'png:compression-level=9',
        path.join(output, filename),
    ]);
}

const master = path.join(output, 'icon-1024.png');
// Draw the source geometry directly: ImageMagick builds without librsvg can
// silently omit SVG strokes. Supersampling keeps every export crisp.
const paths = [...artwork.matchAll(/<path d="([^"]+)"/g)].map(match => match[1]);
const circle = artwork.match(/<circle cx="([^"]+)" cy="([^"]+)" r="([^"]+)"/);
function rasterize(filename, size, strokeWidth, compact = false) {
    const drawing = [
        compact ? `scale ${2048 / 384},${2048 / 384} translate -64,-64` : 'scale 4,4',
        'fill none stroke white', `stroke-width ${strokeWidth}`,
        'stroke-linecap round stroke-linejoin round',
        ...paths.slice(0, -1).map(d => `path '${d}'`),
        `circle ${circle[1]},${circle[2]} ${circle[1]},${Number(circle[2]) - Number(circle[3])}`,
        `fill white stroke none path '${paths[paths.length - 1]}'`,
    ].join(' ');
    execFileSync('magick', [
        '-size', '2048x2048', `xc:${blue}`, '-draw', drawing,
        '-filter', 'Lanczos', '-resize', `${size}x${size}`,
        '-depth', '8', '-strip', path.join(output, filename),
    ]);
}
rasterize('icon-1024.png', 1024, 8);
fs.copyFileSync(source, path.join(output, 'icon.svg'));

for (const size of [192, 512]) {
    render(master, `icon-${size}.png`, ['-resize', `${size}x${size}`]);
    const padded = Math.round(size * 0.88);
    render(master, `maskable-${size}.png`, [
        '-resize', `${padded}x${padded}`, '-background', blue,
        '-gravity', 'center', '-extent', `${size}x${size}`,
    ]);
}
for (const size of [152, 167, 180]) {
    render(master, `apple-touch-icon-${size}.png`, ['-resize', `${size}x${size}`]);
}

// Slightly stronger strokes preserve the fine outline at browser-tab sizes.
const faviconArtwork = artwork.replace('stroke-width="8"', 'stroke-width="16"')
    .replace('viewBox="0 0 512 512"', 'viewBox="64 64 384 384"');
fs.writeFileSync(path.join(output, 'favicon.svg'), faviconArtwork);
for (const size of [16, 32, 48]) {
    rasterize(`favicon-${size}.png`, size, 16, true);
}
execFileSync('magick', [
    ...[16, 32, 48].map(size => path.join(output, `favicon-${size}.png`)),
    path.join(output, 'favicon.ico'),
]);

const links = [
    '{{-- Generated by npm run icons:metronome from resources/artwork/metronome/icon.svg. --}}',
    '<meta name="mobile-web-app-capable" content="yes">',
    '<meta name="apple-mobile-web-app-capable" content="yes">',
    '<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">',
    '<meta name="apple-mobile-web-app-title" content="Metronome">',
];
function link(rel, filename, attributes = '') {
    links.push(`<link rel="${rel}"${attributes} href="{{ asset('/favicon/metronome/${filename}?v=${version}') }}">`);
}
link('manifest', 'manifest.webmanifest');
link('icon', 'favicon.ico', ' type="image/x-icon" sizes="16x16 32x32 48x48"');
for (const size of [16, 32]) link('icon', `favicon-${size}.png`, ` type="image/png" sizes="${size}x${size}"`);
link('icon', 'favicon.svg', ' type="image/svg+xml" sizes="any"');
for (const size of [152, 167, 180]) link('apple-touch-icon', `apple-touch-icon-${size}.png`, ` sizes="${size}x${size}"`);

for (const [width, height, ratio] of screens) {
    for (const orientation of ['portrait', 'landscape']) {
        const pixels = orientation === 'portrait'
            ? [width * ratio, height * ratio] : [height * ratio, width * ratio];
        const filename = `splash-${pixels.join('x')}.png`;
        render(master, filename, [
            '-resize', `${160 * ratio}x${160 * ratio}`, '-background', blue,
            '-gravity', 'center', '-extent', pixels.join('x'),
        ]);
        link('apple-touch-startup-image', filename,
            ` media="screen and (device-width: ${width}px) and (device-height: ${height}px) and (-webkit-device-pixel-ratio: ${ratio}) and (orientation: ${orientation})"`);
    }
}

const icon = (filename, size, purpose) => ({
    src: `${filename}?v=${version}`, sizes: `${size}x${size}`, type: 'image/png', purpose,
});
fs.writeFileSync(path.join(output, 'manifest.webmanifest'), JSON.stringify({
    id: '/',
    name: 'Metronome',
    short_name: 'Metronome',
    description: 'A minimalist metronome. Tap to play, swipe to find your tempo.',
    start_url: '/',
    scope: '/',
    display: 'standalone',
    background_color: blue,
    theme_color: blue,
    icons: [
        ...[192, 512].map(size => icon(`icon-${size}.png`, size, 'any')),
        ...[192, 512].map(size => icon(`maskable-${size}.png`, size, 'maskable')),
    ],
}, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'resources/views/layouts/favicon/metronome.blade.php'), links.join('\n') + '\n');
console.log(`Generated metronome icons and ${screens.length * 2} launch screens (version ${version}).`);
